		/**
		* Register the floating latest-progress dock card, manual check action, presence reporter, and settings page.
		* @param ctx - client plugin context.
		*/
		function apply(ctx) {
			const connection = ctx.get("connection");
			ctx.effect(() => ctx.locale.register("progressCheck", {
				zh,
				en
			}));
			ctx.effect(() => {
				return startPresenceReporter({
					clientId: createClientId(),
					list: ctx.sessions.list,
					send: (presence) => {
						connection.rpc.call(PROGRESS_CHANNEL, PRESENCE_METHOD, presence).catch(() => {});
					}
				});
			});
			const failure = createSnapshotStore(null);
			let failureSequence = 0;
			const onFailure = () => {
				failure.set(++failureSequence);
			};
			const FailureToast = ({ t, useFailure }) => {
				const sequence = useFailure((value) => value);
				return sequence === null ? null : (0, react.createElement)(_deepseek_ai_dsh_client_ui_primitives.Toast, {
					key: sequence,
					icon: (0, react.createElement)(_deepseek_ai_dsh_client_ui_primitives.IconWarningOutlineRegular),
					text: t("generateFailed"),
					onDone: () => {
						failure.set(null);
					}
				});
			};
			ctx.slots.inject("shell.overlay", () => ctx.slots.register({
				name: "shell.overlay",
				id: "progress-check-failure",
				locale: "progressCheck",
				inject: () => ({ hooks: { failure } })
			}, FailureToast));
			const refreshOnTurnEndStore = createSnapshotStore(false);
			ctx.inject(["configForms"], (scope) => {
				const form = scope.configForms.get(PROGRESS_ENTRY_ID);
				const settings = new ProgressSettingsForm(form);
				const syncRefresh = () => {
					refreshOnTurnEndStore.set(form.getSnapshot().value?.refreshOnTurnEnd === true);
				};
				syncRefresh();
				scope.effect(() => form.subscribe(syncRefresh), "progress-check: refreshOnTurnEnd state");
				scope.effect(() => () => {
					settings.dispose();
				}, "progress-check: settings form");
				scope.effect(() => scope.configForms.whileServed([PROGRESS_ENTRY_ID], () => scope.slots.inject("plugins.bundle.config", () => scope.slots.register({
					name: "plugins.bundle.config",
					key: BUNDLE_PACKAGE,
					locale: "progressCheck",
					inject: () => settings.inject()
				}, ProgressSettingsCard))), "progress-check: settings page");
			});
			ctx.effect(() => {
				const style = document.createElement("style");
				style.textContent = styles;
				document.head.append(style);
				return () => style.remove();
			});
			const DockView = ({ useProjection, useSession, t, useInput, inputActions, focusComposer, generate, onFailure }) => {
				const view = useProjection("progress-check");
				const running = useSession((session) => session.running);
				const refreshOnTurnEnd = (0, react.useSyncExternalStore)(refreshOnTurnEndStore.subscribe, refreshOnTurnEndStore.getSnapshot);
				const disabled = useInput((state) => state.phase !== "plain");
				if (view == null) return null;
				return (0, react.createElement)(Card, {
					report: view.report,
					updatedAt: view.updatedAt,
					stepsAgo: view.stepsAgo,
					staleUpdating: refreshOnTurnEnd && !running && view.needsRefresh,
					t,
					disabled,
					action: running ? (0, react.createElement)(GenerateAction, {
						t,
						generate,
						onFailure
					}) : null,
					onReply: (question) => {
						const span = inputActions.captureInsertion();
						const prefix = span.start === 0 ? "" : "\n";
						if (inputActions.insertText(`${prefix}${t("replyTo", { question })}`, {
							...span,
							end: span.start
						})) {
							inputActions.persistDraft();
							focusComposer();
						}
					}
				});
			};
			ctx.slots.inject("conversation.input.dock", () => ctx.slots.register({
				name: "conversation.input.dock",
				id: "progress-check",
				order: -10,
				locale: "progressCheck",
				inject: (sessionId) => ({
					focusComposer: () => {
						const binding = ctx.sessions.binding(sessionId);
						if (binding !== void 0) ctx.conversation.input.for(binding.ctx).focus();
					},
					generate: async (signal) => {
						const result = await connection.rpc.call(PROGRESS_CHANNEL, GENERATE_METHOD, { sessionId }, signal);
						return result.ok && generateResponseSchema.safeParse(result.value).success;
					},
					onFailure
				})
			}, DockView));
		}
